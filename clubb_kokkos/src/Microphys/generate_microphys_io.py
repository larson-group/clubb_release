#!/usr/bin/env python3
"""Generate permanent C++ microphysics and SILHS namelist bindings.

Run this file after changing a namelist in Native init_microphys. The generated
microphys_io.hpp supplies the four existing read_* contracts, including the
flattened scalar arguments for the small slope/intercept and probability
records. Native percent component names remain visible to namelist::Group.

Defaults and scheme/SILHS feature gates stay in init_microphys. Only parsing
and writes to the supplied caller-owned values occur in the generated readers.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path
import re
import sys

SOURCE = Path(__file__).resolve().parent
sys.path.insert(0, str(SOURCE.parent))
import generate_driver_io as driver_io
from fortran_procedures import Argument, declaration, statements
from generate_derived_types import split_top, write_generated


def microphysics_groups() -> list[driver_io.Namelist]:
    """Read Native group order, imported kinds, component names and widths."""
    root = driver_io.ROOT
    source = "src/Microphys/microphys_init_cleanup.F90"
    code = statements((root / source).read_text())
    modules = driver_io.module_declarations()
    resolved = {}
    for statement in code:
        use = re.match(r"use\s+(\w+)\s*,\s*only\s*:\s*(.*)", statement, re.I)
        if not use:
            continue
        for member in split_top(use[2]):
            if "=>" in member:
                alias, name = map(str.strip, member.split("=>"))
            else:
                alias = name = member
            key = (use[1].lower(), name.lower())
            if key in modules:
                resolved[alias.lower()] = replace(modules[key], name=alias)
    for statement in code:
        resolved.update(declaration(statement))
    records = {
        name: driver_io.type_declarations(root / path, name)
        for path, name in [
            ("src/CLUBB_core/corr_varnce_module.F90", "hmp2_ip_on_hmm2_ip_slope_type"),
            ("src/CLUBB_core/corr_varnce_module.F90", "hmp2_ip_on_hmm2_ip_intrcpt_type"),
            ("src/SILHS/parameters_silhs.F90", "eight_cluster_presc_probs_type"),
        ]
    }
    # Default REAL engine settings remain float, unlike core_rknd parameters.
    morrison = (root / "src/Microphys/Morrison_microphys/module_mp_graupel.F90").read_text()
    default_real = set()
    for statement in statements(re.split(r"(?mi)^\s*contains\s*$", morrison, maxsplit=1)[0]):
        if re.match(r"real\s*(?:,|::)", statement, re.I):
            default_real.update(declaration(statement))
    result = []
    for statement in code:
        group = re.match(r"namelist\s*/(\w+)/\s*(.*)", statement, re.I)
        if not group:
            continue
        arguments = [
            Argument("namelist_file", "character", (), "in", False, False, "*"),
            Argument("iunit", "integer", (), "in", False, False),
            Argument("read_status", "integer", (), "out", False, False),
        ]
        bindings = []
        for member in split_top(group[2]):
            argument = resolved[member.lower()]
            if argument.kind in records:
                for field in records[argument.kind].values():
                    flat = member + "__" + field.name
                    arguments.append(replace(field, name=flat, intent="inout"))
                    bindings.append(driver_io.Binding(member + "%" + field.name, flat, field))
            else:
                argument = replace(
                    argument,
                    name=member,
                    kind="float" if member.lower() in default_real else argument.kind,
                    intent="inout",
                    optional=False,
                    allocatable=False,
                )
                arguments.append(argument)
                bindings.append(driver_io.Binding(member, member, argument))
        result.append(
            driver_io.Namelist(group[1], source, arguments, bindings, "namelist_file", ("iunit",))
        )
    return result


def main() -> None:
    """Regenerate the four typed readers without invoking a Fortran service."""
    text = driver_io.render_header(
        [
            "// Read microphysics and SILHS namelists into initialized case values.",
            "//",
            "// Public readers: read_microphysics_setting, read_gfdl_activation_setting,",
            "// read_silhs_params_nl and read_configurable_silhs_flags_nl. The caller owns",
            "// defaults, feature gates and all mutable values. Native percent component",
            "// names, fixed character widths and default-real float kinds are preserved.",
            "// Generated by Microphys/generate_microphys_io.py from init_microphys.",
        ],
        microphysics_groups(),
        [],
    )
    write_generated(SOURCE / "microphys_io.hpp", text)
    print("Permanent microphysics/SILHS namelist bindings: 4")


if __name__ == "__main__":
    main()
