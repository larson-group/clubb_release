def configure_environment(
    env: MutableMapping[str, str], tools_dir: Path | None = None,
    xla_prealloc: bool = False,
) -> None:
    """Apply the CPU compiler workaround to XLA_FLAGS in the supplied environment.

    CPU compilation can incorrectly duplicate an independent array row in
    ordinary code, including code generated by reverse AD:
    https://github.com/jax-ml/jax/issues/42185
    Reproduced with JAX/jaxlib 0.11.0 and 0.12.0.1 on x86 CPU. Disable generic
    LLVM DAG combining to avoid it in all CPU runs, with or without gradients;
    retain JIT and other optimizations. Revisit this setting when the upstream
    defect is resolved.

    CUDA 0.11.0 controls pass on RTX 2060/3080: the reproducer and short
    two-column model gradients agree with their references. Six-hour gradients
    also agree on RTX 3080. Keep this policy CPU-only; other CUDA versions,
    ROCm and Metal remain unvalidated.
    GPU reproducer controls: https://github.com/jax-ml/jax/issues/42185#issuecomment-6537683779

    The launcher applies this before starting JAX. Direct model imports apply
    the same policy and must precede JAX backend initialization; restart any
    already initialized processes.
    Preserve inherited XLA/LLVM options, replace a conflicting combiner setting,
    and avoid duplicate options on repeated calls. tools_dir and xla_prealloc
    belong to the shared backend hook and are unused for CPU.
    """
    flags = []
    extra_options = []
    inherited = iter(shlex.split(env.get("XLA_FLAGS", "")))
    for flag in inherited:
        if flag == "--xla_backend_extra_options":
            value = next(inherited, "")
        elif flag.startswith("--xla_backend_extra_options="):
            value = flag.split("=", 1)[1]
        else:
            flags.append(flag)
            continue
        extra_options.extend(option for option in value.split(",")
                             if option and option.split("=", 1)[0].lstrip("-") != "combiner-disabled")
    extra_options.append("--combiner-disabled=true")
    flags.append("--xla_backend_extra_options=" + ",".join(extra_options))
    formatted = []
    for flag in flags:
        if any(char.isspace() or char in "'\"\\" for char in flag):
            name, separator, value = flag.partition("=")
            # XLA expects quoting around values; shell-style quoting of an
            # entire --flag=value token is interpreted as a flags filename.
            flag = name + "=" + json.dumps(value) if separator else json.dumps(flag)
        formatted.append(flag)
    env["XLA_FLAGS"] = " ".join(formatted)


def hardware_info() -> dict[str, object]:
    model = ""
    try:
        for line in Path("/proc/cpuinfo").read_text(
            encoding="utf-8", errors="replace"
        ).splitlines():
            if line.lower().startswith(("model name", "hardware")) and ":" in line:
                model = line.split(":", 1)[1].strip()
                break
    except OSError:
        pass
    if not model and platform.system() == "Darwin":
        try:
            model = subprocess.check_output(
                ["/usr/sbin/sysctl", "-n", "machdep.cpu.brand_string"],
                text=True,
                stderr=subprocess.DEVNULL,
                timeout=2,
            ).strip()
        except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
            pass
    model = model or platform.processor().strip()
    return {
        "model": model or platform.machine() or "Unknown CPU",
        "logical_cpus": os.cpu_count(),
    }


def inspect_devices():
    return [], GpuSelection((), None, order_known=False), True, ""


def format_devices(info: dict[str, object], section_divider: str) -> list[str]:
    hardware = info["hardware"]
    lines = []
    cpu = hardware["cpu"]
    count = cpu.get("logical_cpus")
    suffix = f" ({count} logical CPUs)" if count else ""
    lines.extend(
        [
            section_divider,
            " COMPUTE DEVICE",
            section_divider,
            f" CPU: {cpu['model']}{suffix}",
        ]
    )
    return lines
