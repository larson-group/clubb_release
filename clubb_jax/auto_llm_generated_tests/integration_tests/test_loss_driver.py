"""Check reusable JAX loss sessions against native loss-driver contracts.

The repeated-call and changed-parameter scenarios follow
src/clubb_loss_driver_test.F90 (run_manual_loss_bfb_test,
run_tweaked_parameter_test and run_reinitialize_loss_bfb_test). Scoring and
successive-window behavior come from src/clubb_loss_driver.F90
(clubb_get_loss_for_params, prepare_loss_request_for_scoring and
calculate_field_loss).

A ten-step BOMEX fixture scores two fields in two windows against synthetic
benchmark profiles, with four parameter columns and runtime width two. Checks
cover exact repeated results, refreshed derived state, benchmark boundaries,
invalid-candidate isolation and lifecycle/configuration errors. Fixed-shape
short batches and compilation-cache reuse are additional JAX assertions.
The C8 gradient check compares both window losses with centered differences.

The numerical oracle runs the native loss executable and compares all four
reported metrics at its text-output precision. Build
install/latest/clubb_standalone_loss or set CLUBB_TEST_LOSS_EXE to that executable. Temporary
namelists and benchmark files are generated by the fixture; no F2PY is used.
"""
