def iter_term_occurrences():
    """Yield unique occurrence IDs and their equation-enriched metadata."""
    for group in EQUATION_GROUPS:
        for eq in group["equations"]:
            for position, item in enumerate(eq["terms"]):
                occurrence = f"{eq['id']}--{position}--{item['key']}"
                yield occurrence, {
                    **item,
                    "equation_title": eq["title"],
                    "equation_lhs": eq["lhs"],
                    "equation_source": eq["source"],
                }


