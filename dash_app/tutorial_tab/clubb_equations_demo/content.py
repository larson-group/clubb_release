OWNERSHIP_META = {
    "host": ("Host / physics", "Predicted by the host model, microphysics, or radiation."),
    "clubb_output": ("CLUBB → host", "Predicted by CLUBB and returned to the host model."),
    "clubb_internal": ("CLUBB internal", "Predicted and used internally by CLUBB."),
    "pdf": ("PDF diagnosed", "Calculated by integrating or diagnosing CLUBB's subgrid PDF."),
    "classical": ("Non-PDF closure", "Closed by a classical CLUBB parameterization rather than the PDF."),
}


def term(
    key,
    latex,
    code,
    process,
    title,
    meaning,
    obtained,
    why,
    *,
    ownership=None,
    units="Depends on the selected equation",
    source="doc/CLUBBeqns.tex",
):
    if ownership is None:
        ownership = {
            "forcing": "host",
            "numerical": "classical",
            "pressure": "classical",
            "dissipation": "classical",
            "pdf": "pdf",
            "cloud": "pdf",
            "buoyancy": "pdf",
        }.get(process, "clubb_internal")
    return {
        "key": key,
        "latex": latex,
        "code": code,
        "process": process,
        "ownership": ownership,
        "title": title,
        "meaning": meaning,
        "obtained": obtained,
        "why": why,
        "units": units,
        "source": source,
    }


def equation(
    identifier,
    title,
    lhs,
    summary,
    terms,
    *,
    note,
    source,
    family,
    lhs_owner="clubb_internal",
):
    return {
        "id": identifier,
        "title": title,
        "lhs": lhs,
        "summary": summary,
        "terms": tuple(terms),
        "note": note,
        "source": source,
        "family": family,
        "lhs_owner": lhs_owner,
    }


